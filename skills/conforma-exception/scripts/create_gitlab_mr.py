def _build_commit_message(
    rule: str,
    components: list[str],
    rhoai_version: str,
    effective_until: str,
    rhoaieng_url: str | None = None,
    reference_url: str | None = None,
    spreadsheet_url: str | None = None,
    target_file: str | None = None,
    exception_risk: str | None = None,
    exception_remediation: str | None = None,
) -> str:
    """Build a structured, multi-line commit message with provenance."""
    subject = f"Add conforma exception: {rule} ({rhoai_version})"

    lines = [
        subject,
        "",
        "Exception details:",
        f"  Rule: {rule}",
        f"  RHOAI version: {rhoai_version}",
        f"  Effective until: {effective_until}",
        f"  Components: {', '.join(components)}",
    ]

    if target_file:
        lines.append(f"  Policy file: {target_file}")

    if exception_risk:
        lines.append(f"  Risk: {exception_risk}")
    if exception_remediation:
        lines.append(f"  Remediation: {exception_remediation}")

    lines.append("")

    if rhoaieng_url:
        lines.append(f"RHOAIENG: {rhoaieng_url}")
    if reference_url:
        lines.append(f"Reference: {reference_url}")
    if spreadsheet_url:
        lines.append(f"Spreadsheet: {spreadsheet_url}")

    if rhoaieng_url or reference_url or spreadsheet_url:
        lines.append("")

    lines.extend(
        [
            "---",
            f"Generated by: {PROVENANCE_SKILL}",
            f"Source: https://github.com/{PROVENANCE_REPO}",
            f"User: {getpass.getuser()}@{platform.node()}",
        ]
    )

    return "\n".join(lines)


