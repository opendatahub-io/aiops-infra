def detect_component_type(components: list[str]) -> str:
    """Detect if components are FBC or registry type."""
    for comp in components:
        if "fbc" in comp.lower():
            return "fbc"
    return "registry"


def get_target_file(component_type: str, environment: str, is_self_service: bool) -> str:
    """Determine the target policy file path using discovery or pattern matching."""
    if is_self_service:
        path = _resolve_self_service_file(
            component_type, environment, _get_discovered_self_service_files()
        )
    else:
        path = _resolve_policy_file(
            component_type, environment, _get_discovered_ec_files()
        )
    return _validate_repo_relative_path(path)


def generate_exception_yaml(
    rule: str,
    components: list[str],
    effective_until: str,
    reference_url: str,
    rhoaieng_url: str | None,
    rhoai_version: str,
    is_self_service: bool,
    is_weekday_restriction: bool = False,
    image_ref: str | None = None,
    reference_title: str | None = None,
    spreadsheet_url: str | None = None,
) -> str:
    """Generate the YAML exception block to append.

    Components must be Konflux component names (with -vX-Y suffix), NOT container
    image names (which end in -rhel9/-ubi9). validate_inputs.py enforces this.
    """
    if is_self_service and is_weekday_restriction and image_ref:
        return f"- value: {rule}\n  imageRef: {image_ref}\n"

    if is_self_service:
        lines = [f"- value: {rule}"]
        lines.append("  componentNames:")
        for comp in components:
            lines.append(f"    - {comp}")
        if effective_until:
            lines.append(f'  effectiveUntil: "{effective_until}"')
        return "\n".join(lines) + "\n"

    indent = "          "
    lines = []
    if rhoaieng_url:
        lines.append(f"{indent}# {rhoaieng_url}")
    lines.append(f"{indent}# impacted versions: {rhoai_version}")
    if spreadsheet_url:
        lines.append(f"{indent}# spreadsheet: {spreadsheet_url}")
    lines.append(f"{indent}- value: {rule}")
    lines.append(f"{indent}  componentNames:")
    for comp in components:
        lines.append(f"{indent}    - {comp}")
    lines.append(f'{indent}  effectiveUntil: "{effective_until}"')
    if reference_title:
        lines.append(f"{indent}  reference: {reference_url}  # {reference_title}")
    else:
        lines.append(f"{indent}  reference: {reference_url}")
    return "\n".join(lines) + "\n"


def _find_existing_exceptions(content: str, rule: str, indent: str = "          ") -> list[dict]:
    """Find existing exception blocks for a given rule in the policy file content.

    Returns a list of dicts with:
      - start: line index where the block starts (the `- value:` line)
      - end: line index where the block ends (exclusive)
      - has_component_names: whether the block uses componentNames
      - component_names: list of component names (empty if not used)
      - image_url: imageUrl value if present (empty string if not)
      - effective_until_line: line index of the effectiveUntil line (or None)
      - effective_until_value: current effectiveUntil value (or None)
    """
    lines = content.split("\n")
    results = []
    value_pattern = re.compile(rf"^{re.escape(indent)}- value:\s*(.+)$")
    i = 0
    while i < len(lines):
        match = value_pattern.match(lines[i])
        if match and match.group(1).strip() == rule:
            block_start = i
            block_info: dict = {
                "start": block_start,
                "end": block_start + 1,
                "has_component_names": False,
                "component_names": [],
                "image_url": "",
                "effective_until_line": None,
                "effective_until_value": None,
            }
            i += 1
            while i < len(lines):
                line = lines[i]
                if not line.strip() or value_pattern.match(line):
                    break
                if line.startswith(f"{indent}#"):
                    break
                if line.strip().startswith("- value:"):
                    break
                if "componentNames:" in line:
                    block_info["has_component_names"] = True
                    i += 1
                    while i < len(lines) and lines[i].strip().startswith("- "):
                        comp = lines[i].strip().lstrip("- ").strip()
                        block_info["component_names"].append(comp)
                        block_info["end"] = i + 1
                        i += 1
                    continue
                if "imageUrl:" in line:
                    iu_match = re.search(r'imageUrl:\s*"?([^"]+)"?', line)
                    if iu_match:
                        block_info["image_url"] = iu_match.group(1).strip()
                if "effectiveUntil:" in line:
                    block_info["effective_until_line"] = i
                    eu_match = re.search(r'effectiveUntil:\s*"?([^"]+)"?', line)
                    if eu_match:
                        block_info["effective_until_value"] = eu_match.group(1).strip()
                block_info["end"] = i + 1
                i += 1
            results.append(block_info)
        else:
            i += 1
    return results


def _update_effective_until_in_content(content: str, line_idx: int, new_effective_until: str) -> str:
    """Replace the effectiveUntil value at the given line index."""
    lines = content.split("\n")
    old_line = lines[line_idx]
    new_line = re.sub(
        r'effectiveUntil:\s*"[^"]*"',
        f'effectiveUntil: "{new_effective_until}"',
        old_line,
    )
    if new_line == old_line:
        new_line = re.sub(
            r"effectiveUntil:\s*\S+",
            f'effectiveUntil: "{new_effective_until}"',
            old_line,
        )
    lines[line_idx] = new_line
    return "\n".join(lines)


def remove_exception_from_policy_file(
    file_path: Path,
    rule: str,
    effective_until: str,
    components: list[str] | None = None,
) -> dict:
    """Remove an expired exception block and its preceding comment header.

    The block is identified by matching rule + effectiveUntil + components.
    For unscoped exceptions (no componentNames), only rule + effectiveUntil
    are needed.

    Returns:
        {"action": "removed", "detail": "...", "lines_removed": N}
        or {"action": "not_found", "detail": "..."}
    """
    content = file_path.read_text(encoding="utf-8")
    indent = "          "
    existing = _find_existing_exceptions(content, rule, indent)

    target_block = None
    for block in existing:
        if block["effective_until_value"] != effective_until:
            continue
        if components and block["has_component_names"]:
            if sorted(block["component_names"]) == sorted(components):
                target_block = block
                break
        elif not components and not block["has_component_names"]:
            target_block = block
            break
        elif components and not block["has_component_names"]:
            target_block = block
            break

    if not target_block:
        return {
            "action": "not_found",
            "detail": (
                f"No matching exception block found for rule={rule}, "
                f"effectiveUntil={effective_until}, components={components}"
            ),
        }

    lines = content.split("\n")
    block_start = target_block["start"]
    block_end = target_block["end"]

    comment_start = block_start
    i = block_start - 1
    while i >= 0:
        stripped = lines[i].strip()
        if stripped.startswith("#") and lines[i].startswith(indent):
            comment_start = i
            i -= 1
        elif stripped == "":
            i -= 1
        else:
            break

    del lines[comment_start:block_end]
    while comment_start < len(lines) and lines[comment_start].strip() == "":
        del lines[comment_start]

    file_path.write_text("\n".join(lines), encoding="utf-8")
    lines_removed = block_end - comment_start
    return {
        "action": "removed",
        "detail": (
            f"Removed expired exception for {rule} "
            f"(lines {comment_start + 1}-{block_end}, effectiveUntil={effective_until})"
        ),
        "lines_removed": lines_removed,
    }


def apply_exception_to_policy_file(
    file_path: Path,
    yaml_block: str,
    is_self_service: bool,
    rule: str,
    components: list[str],
    effective_until: str,
) -> dict:
    """Apply exception to the policy file with deduplication logic.

    Returns a dict with:
      - action: "appended" | "extended" | "appended_new_style"
      - detail: human-readable description of what was done
    """
    content = file_path.read_text(encoding="utf-8")

    if is_self_service:
        if content.rstrip().endswith("---"):
            content = content.rstrip() + "\n"
        content += yaml_block
        file_path.write_text(content, encoding="utf-8")
        return {"action": "appended", "detail": "Appended self-service exception"}

    existing = _find_existing_exceptions(content, rule)

    if not existing:
        content = content.rstrip() + "\n" + yaml_block
        file_path.write_text(content, encoding="utf-8")
        return {"action": "appended", "detail": "No existing exception for this rule; appended new block"}

    sorted_components = sorted(components)
    for exc in existing:
        if exc["has_component_names"]:
            if sorted(exc["component_names"]) == sorted_components:
                if exc["effective_until_line"] is not None:
                    content = _update_effective_until_in_content(content, exc["effective_until_line"], effective_until)
                    file_path.write_text(content, encoding="utf-8")
                    old_date = exc["effective_until_value"] or "unknown"
                    return {
                        "action": "extended",
                        "detail": (
                            f"Extended existing exception effectiveUntil from "
                            f"{old_date} to {effective_until} "
                            f"(componentNames matched)"
                        ),
                    }

    has_old_style = any(not exc["has_component_names"] for exc in existing)
    if has_old_style:
        content = content.rstrip() + "\n" + yaml_block
        file_path.write_text(content, encoding="utf-8")
        return {
            "action": "appended_new_style",
            "detail": (
                "Old-style exception (no componentNames) found for this rule; "
                "left intact and appended new componentNames-based exception"
            ),
        }

    content = content.rstrip() + "\n" + yaml_block
    file_path.write_text(content, encoding="utf-8")
    return {
        "action": "appended",
        "detail": ("Existing exception found for this rule but with different componentNames; appended new block"),
    }


def append_to_policy_file(file_path: Path, yaml_block: str, is_self_service: bool) -> None:
    """Append the exception block to the target file (deprecated interface)."""
    content = file_path.read_text(encoding="utf-8")

    if is_self_service:
        if content.rstrip().endswith("---"):
            content = content.rstrip() + "\n"
        content += yaml_block
    else:
        content = content.rstrip() + "\n" + yaml_block

    file_path.write_text(content, encoding="utf-8")


def create_mr(
    rule: str,
    components: list[str],
    effective_until: str,
    reference_url: str,
    rhoaieng_url: str | None,
    rhoai_version: str,
    environment: str,
    is_self_service: bool,
    is_weekday_restriction: bool = False,
    image_ref: str | None = None,
    reference_title: str | None = None,
    spreadsheet_url: str | None = None,
    vendor_tag: str | None = None,
    exception_risk: str | None = None,
    exception_remediation: str | None = None,
    policy_file: str | None = None,
    dry_run: bool = False,
) -> dict:
    """Clone repo, append exception, create MR."""
    component_type = detect_component_type(components)
    if policy_file:
        target_file = _validate_repo_relative_path(policy_file, "policy-file argument")
    else:
        target_file = get_target_file(component_type, environment, is_self_service)

    yaml_block = generate_exception_yaml(
        rule=rule,
        components=components,
        effective_until=effective_until,
        reference_url=reference_url,
        rhoaieng_url=rhoaieng_url,
        rhoai_version=rhoai_version,
        is_self_service=is_self_service,
        is_weekday_restriction=is_weekday_restriction,
        image_ref=image_ref,
        reference_title=reference_title,
        spreadsheet_url=spreadsheet_url,
    )

    if dry_run:
        return {
            "status": "dry_run",
            "target_file": target_file,
            "yaml_block": yaml_block,
            "component_type": component_type,
            "mr_url": None,
            "dedup_note": (
                "At execution time, the script will check if an exception for this "
                "rule already exists: if it uses componentNames and they match, "
                "effectiveUntil will be extended in-place; if old-style (no "
                "componentNames), it will be left intact and a new block appended."
            ),
        }

    WORK_DIR.mkdir(parents=True, exist_ok=True)
    workdir = Path(tempfile.mkdtemp(prefix="conforma-exception-mr-", dir=WORK_DIR))
    try:
        clone_dest = str(workdir / "repo")
        repo_url = _get_authenticated_repo_url()
        _run_git(
            [
                "git",
                "clone",
                "--depth=1",
                "--branch",
                DEFAULT_BRANCH,
                "--filter=blob:none",
                "--sparse",
                repo_url,
                clone_dest,
            ],
            timeout=300,
        )
        repo_dir = workdir / "repo"
        policy_dir = str(Path(target_file).parent)
        _run_git(["git", "sparse-checkout", "set", policy_dir], cwd=repo_dir)

        branch_name = _make_branch_name(rule, rhoai_version, components)
        _run_git(["git", "checkout", "-b", branch_name], cwd=repo_dir)

        policy_file = repo_dir / target_file
        if not policy_file.exists():
            return {
                "status": "failed",
                "error": f"Target file not found: {target_file}",
                "target_file": target_file,
                "mr_url": None,
            }

        apply_result = apply_exception_to_policy_file(
            file_path=policy_file,
            yaml_block=yaml_block,
            is_self_service=is_self_service,
            rule=rule,
            components=components,
            effective_until=effective_until,
        )

        action = apply_result["action"]
        if action == "extended":
            commit_msg = _build_commit_message_extend(
                rule=rule,
                components=components,
                rhoai_version=rhoai_version,
                effective_until=effective_until,
                rhoaieng_url=rhoaieng_url,
                reference_url=reference_url,
                spreadsheet_url=spreadsheet_url,
                target_file=target_file,
                exception_risk=exception_risk,
                exception_remediation=exception_remediation,
            )
        else:
            commit_msg = _build_commit_message(
                rule=rule,
                components=components,
                rhoai_version=rhoai_version,
                effective_until=effective_until,
                rhoaieng_url=rhoaieng_url,
                reference_url=reference_url,
                spreadsheet_url=spreadsheet_url,
                target_file=target_file,
                exception_risk=exception_risk,
                exception_remediation=exception_remediation,
            )

        _run_git(["git", "add", target_file], cwd=repo_dir)
        _run_git(["git", "commit", "-m", commit_msg], cwd=repo_dir)
        push_result = subprocess.run(
            ["git", "push", "-u", "origin", branch_name],
            capture_output=True,
            text=True,
            timeout=60,
            cwd=repo_dir,
            env=gitlab_ops.git_env(),
        )

        use_fork = False
        if push_result.returncode != 0:
            fork_url = _ensure_fork(repo_dir)
            if not fork_url:
                return {
                    "status": "failed",
                    "error": (f"Push failed and fork creation failed: {push_result.stderr.strip()}"),
                    "target_file": target_file,
                    "branch": branch_name,
                    "mr_url": None,
                }
            _run_git(["git", "remote", "add", "fork", fork_url], cwd=repo_dir)
            _run_git(["git", "push", "-u", "fork", branch_name], cwd=repo_dir)
            use_fork = True

        mr_title = _build_mr_title(rule, rhoai_version, environment, vendor_tag)
        mr_body = _build_mr_body(
            rule=rule,
            components=components,
            rhoai_version=rhoai_version,
            effective_until=effective_until,
            rhoaieng_url=rhoaieng_url,
            reference_url=reference_url,
            spreadsheet_url=spreadsheet_url,
            target_file=target_file,
        )
        mr_create_args = [
            "mr",
            "create",
            "--title",
            mr_title,
            "--description",
            mr_body,
            "--target-branch",
            DEFAULT_BRANCH,
            "--remove-source-branch",
            "-R",
            f"{GITLAB_HOST}/{GITLAB_PROJECT}",
        ]
        if use_fork:
            mr_create_args.extend(["--head", branch_name])

        mr_result = subprocess.run(
            ["glab", *mr_create_args],
            capture_output=True,
            text=True,
            timeout=30,
            cwd=repo_dir,
        )

        if mr_result.returncode != 0:
            return {
                "status": "failed",
                "error": mr_result.stderr.strip() or mr_result.stdout.strip(),
                "target_file": target_file,
                "branch": branch_name,
                "mr_url": None,
                "use_fork": use_fork,
            }

        mr_url = _extract_mr_url(mr_result.stdout + mr_result.stderr)
        return {
            "status": "created",
            "target_file": target_file,
            "branch": branch_name,
            "mr_url": mr_url,
            "yaml_block": yaml_block,
            "component_type": component_type,
            "use_fork": use_fork,
            "apply_action": apply_result["action"],
            "apply_detail": apply_result["detail"],
        }
    except subprocess.CalledProcessError as exc:
        return {
            "status": "failed",
            "error": f"Git operation failed: {exc.stderr or exc.stdout}",
            "target_file": target_file,
            "mr_url": None,
        }
    finally:
        import shutil

        shutil.rmtree(workdir, ignore_errors=True)


def update_mr(
    branch_name: str,
    rule: str,
    components: list[str],
    effective_until: str,
    reference_url: str,
    rhoaieng_url: str | None,
    rhoai_version: str,
    environment: str,
    is_self_service: bool,
    is_weekday_restriction: bool = False,
    image_ref: str | None = None,
    reference_title: str | None = None,
    spreadsheet_url: str | None = None,
    vendor_tag: str | None = None,
    exception_risk: str | None = None,
    exception_remediation: str | None = None,
    policy_file: str | None = None,
    dry_run: bool = False,
) -> dict:
    """Update an existing MR branch by recreating it from current main.

    Always clones from main first to maintain proper merge-base ancestry,
    then creates the branch, applies the exception, and force-pushes.
    This avoids disconnected-history issues that cause GitLab to show
    hundreds of unrelated file changes in the MR diff.
    """
    component_type = detect_component_type(components)
    if policy_file:
        target_file = _validate_repo_relative_path(policy_file, "policy-file argument")
    else:
        target_file = get_target_file(component_type, environment, is_self_service)

    yaml_block = generate_exception_yaml(
        rule=rule,
        components=components,
        effective_until=effective_until,
        reference_url=reference_url,
        rhoaieng_url=rhoaieng_url,
        rhoai_version=rhoai_version,
        is_self_service=is_self_service,
        is_weekday_restriction=is_weekday_restriction,
        image_ref=image_ref,
        reference_title=reference_title,
        spreadsheet_url=spreadsheet_url,
    )

    if dry_run:
        return {
            "status": "dry_run",
            "target_file": target_file,
            "yaml_block": yaml_block,
            "branch": branch_name,
            "component_type": component_type,
            "mr_url": None,
        }

    WORK_DIR.mkdir(parents=True, exist_ok=True)
    workdir = Path(tempfile.mkdtemp(prefix="conforma-exception-mr-update-", dir=WORK_DIR))
    try:
        clone_dest = str(workdir / "repo")
        repo_url = _get_authenticated_repo_url()
        _run_git(
            [
                "git",
                "clone",
                "--depth=1",
                "--branch",
                DEFAULT_BRANCH,
                "--filter=blob:none",
                "--sparse",
                repo_url,
                clone_dest,
            ],
            timeout=300,
        )
        repo_dir = workdir / "repo"
        policy_dir = str(Path(target_file).parent)
        _run_git(["git", "sparse-checkout", "set", policy_dir], cwd=repo_dir)

        _run_git(["git", "checkout", "-b", branch_name], cwd=repo_dir)

        policy_file = repo_dir / target_file
        if not policy_file.exists():
            return {
                "status": "failed",
                "error": f"Target file not found: {target_file}",
                "target_file": target_file,
                "mr_url": None,
            }

        apply_result = apply_exception_to_policy_file(
            file_path=policy_file,
            yaml_block=yaml_block,
            is_self_service=is_self_service,
            rule=rule,
            components=components,
            effective_until=effective_until,
        )

        action = apply_result["action"]
        if action == "extended":
            commit_msg = _build_commit_message_extend(
                rule=rule,
                components=components,
                rhoai_version=rhoai_version,
                effective_until=effective_until,
                rhoaieng_url=rhoaieng_url,
                reference_url=reference_url,
                spreadsheet_url=spreadsheet_url,
                target_file=target_file,
                exception_risk=exception_risk,
                exception_remediation=exception_remediation,
            )
        else:
            commit_msg = _build_commit_message(
                rule=rule,
                components=components,
                rhoai_version=rhoai_version,
                effective_until=effective_until,
                rhoaieng_url=rhoaieng_url,
                reference_url=reference_url,
                spreadsheet_url=spreadsheet_url,
                target_file=target_file,
                exception_risk=exception_risk,
                exception_remediation=exception_remediation,
            )

        _run_git(["git", "add", target_file], cwd=repo_dir)
        _run_git(["git", "commit", "-m", commit_msg], cwd=repo_dir)

        push_result = subprocess.run(
            ["git", "push", "--force", "origin", f"HEAD:{branch_name}"],
            capture_output=True,
            text=True,
            timeout=60,
            cwd=repo_dir,
            env=gitlab_ops.git_env(),
        )
        if push_result.returncode != 0:
            return {
                "status": "failed",
                "error": f"Force push failed: {push_result.stderr.strip()}",
                "target_file": target_file,
                "branch": branch_name,
                "mr_url": None,
            }

        mr_url = _extract_mr_url(push_result.stdout + push_result.stderr)

        new_title = _build_mr_title(rule, rhoai_version, environment, vendor_tag)
        new_body = _build_mr_body(
            rule=rule,
            components=components,
            rhoai_version=rhoai_version,
            effective_until=effective_until,
            rhoaieng_url=rhoaieng_url,
            reference_url=reference_url,
            spreadsheet_url=spreadsheet_url,
            target_file=target_file,
        )
        sync_result = _sync_mr_description(branch_name, new_title, new_body)
        if sync_result and sync_result.get("mr_url") and not mr_url:
            mr_url = sync_result["mr_url"]

        return {
            "status": "updated",
            "target_file": target_file,
            "branch": branch_name,
            "mr_url": mr_url,
            "yaml_block": yaml_block,
            "component_type": component_type,
            "apply_action": apply_result["action"],
            "apply_detail": apply_result["detail"],
        }
    except subprocess.CalledProcessError as exc:
        return {
            "status": "failed",
            "error": f"Git operation failed: {exc.stderr or exc.stdout}",
            "target_file": target_file,
            "mr_url": None,
        }
    finally:
        import shutil

        shutil.rmtree(workdir, ignore_errors=True)


def _sync_mr_description(
    branch_name: str,
    title: str,
    body: str,
) -> dict | None:
    """Find the open MR for branch_name and update its title + description.

    Returns the update result dict, or None if no open MR was found.
    """
    mrs = gitlab_ops.find_mr(GITLAB_PROJECT, source_branch=branch_name, state="opened")
    if not mrs or mrs[0].get("error"):
        return None
    mr_iid = mrs[0]["mr_iid"]
    return gitlab_ops.update_mr(GITLAB_PROJECT, mr_iid, title=title, description=body)


def update_consolidated_mr(
    branch_name: str,
    rule: str,
    version_specs: list[dict],
    reference_url: str,
    rhoaieng_url: str | None,
    environment: str,
    is_self_service: bool,
    reference_title: str | None = None,
    spreadsheet_url: str | None = None,
    vendor_tag: str | None = None,
    exception_risk: str | None = None,
    exception_remediation: str | None = None,
    policy_file: str | None = None,
    dry_run: bool = False,
) -> dict:
    """Update an existing consolidated MR branch from current main.

    Same pattern as update_mr() but for multi-version exception Merge Requests.
    After force-pushing, syncs the MR title and description to reflect
    the current version_specs.
    """
    if not version_specs:
        return {"status": "failed", "error": "No version_specs provided", "mr_url": None}

    all_components = []
    for spec in version_specs:
        all_components.extend(spec["components"])
    component_type = detect_component_type(all_components)
    if policy_file:
        target_file = _validate_repo_relative_path(policy_file, "policy-file argument")
    else:
        target_file = get_target_file(component_type, environment, is_self_service)

    if dry_run:
        yaml_blocks = []
        for spec in version_specs:
            block = generate_exception_yaml(
                rule=rule,
                components=spec["components"],
                effective_until=spec["effective_until"],
                reference_url=reference_url,
                rhoaieng_url=rhoaieng_url,
                rhoai_version=spec["version"],
                is_self_service=is_self_service,
                reference_title=reference_title,
                spreadsheet_url=spreadsheet_url,
            )
            yaml_blocks.append({"version": spec["version"], "yaml": block})
        return {
            "status": "dry_run",
            "target_file": target_file,
            "yaml_blocks": yaml_blocks,
            "branch": branch_name,
            "component_type": component_type,
            "versions": [s["version"] for s in version_specs],
            "mr_url": None,
        }

