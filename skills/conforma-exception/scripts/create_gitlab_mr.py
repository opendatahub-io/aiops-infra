def create_consolidated_mr(
    rule: str,
    version_specs: list[dict],
    reference_url: str,
    rhoaieng_url: str | None,
    environment: str,
    is_self_service: bool,
    reference_title: str | None = None,
    spreadsheet_url: str | None = None,
    vendor_tag: str | None = None,
    exception_risk: str | None = None,
    exception_remediation: str | None = None,
    policy_file: str | None = None,
    dry_run: bool = False,
) -> dict:
    """Create a single consolidated MR covering all RHOAI versions for one rule.

    version_specs is a list of dicts:
        [{"version": "rhoai-3.3", "components": [...], "effective_until": "..."}, ...]

    All version blocks are appended to the same policy file in a single commit.
    """
    if not version_specs:
        return {"status": "failed", "error": "No version_specs provided", "mr_url": None}

    all_components = []
    for spec in version_specs:
        all_components.extend(spec["components"])
    component_type = detect_component_type(all_components)
    if policy_file:
        target_file = _validate_repo_relative_path(policy_file, "policy-file argument")
    else:
        target_file = get_target_file(component_type, environment, is_self_service)

    if dry_run:
        yaml_blocks = []
        for spec in version_specs:
            block = generate_exception_yaml(
                rule=rule,
                components=spec["components"],
                effective_until=spec["effective_until"],
                reference_url=reference_url,
                rhoaieng_url=rhoaieng_url,
                rhoai_version=spec["version"],
                is_self_service=is_self_service,
                reference_title=reference_title,
                spreadsheet_url=spreadsheet_url,
            )
            yaml_blocks.append({"version": spec["version"], "yaml": block})
        return {
            "status": "dry_run",
            "target_file": target_file,
            "yaml_blocks": yaml_blocks,
            "component_type": component_type,
            "versions": [s["version"] for s in version_specs],
            "mr_url": None,
        }

    WORK_DIR.mkdir(parents=True, exist_ok=True)
    workdir = Path(tempfile.mkdtemp(prefix="conforma-exception-mr-consolidated-", dir=WORK_DIR))
    try:
        clone_dest = str(workdir / "repo")
        repo_url = _get_authenticated_repo_url()
        _run_git(
            [
                "git",
                "clone",
                "--depth=1",
                "--branch",
                DEFAULT_BRANCH,
                "--filter=blob:none",
                "--sparse",
                repo_url,
                clone_dest,
            ],
            timeout=300,
        )
        repo_dir = workdir / "repo"
        policy_dir = str(Path(target_file).parent)
        _run_git(["git", "sparse-checkout", "set", policy_dir], cwd=repo_dir)

        branch_name = _make_branch_name_consolidated(rule, version_specs)
        _run_git(["git", "checkout", "-b", branch_name], cwd=repo_dir)

        policy_file = repo_dir / target_file
        if not policy_file.exists():
            return {
                "status": "failed",
                "error": f"Target file not found: {target_file}",
                "target_file": target_file,
                "mr_url": None,
            }

        apply_results = []
        for spec in version_specs:
            yaml_block = generate_exception_yaml(
                rule=rule,
                components=spec["components"],
                effective_until=spec["effective_until"],
                reference_url=reference_url,
                rhoaieng_url=rhoaieng_url,
                rhoai_version=spec["version"],
                is_self_service=is_self_service,
                reference_title=reference_title,
                spreadsheet_url=spreadsheet_url,
            )
            result = apply_exception_to_policy_file(
                file_path=policy_file,
                yaml_block=yaml_block,
                is_self_service=is_self_service,
                rule=rule,
                components=spec["components"],
                effective_until=spec["effective_until"],
            )
            apply_results.append(
                {
                    "version": spec["version"],
                    "action": result["action"],
                    "detail": result["detail"],
                }
            )

        commit_msg = _build_commit_message_consolidated(
            rule=rule,
            version_specs=version_specs,
            rhoaieng_url=rhoaieng_url,
            reference_url=reference_url,
            spreadsheet_url=spreadsheet_url,
            target_file=target_file,
            exception_risk=exception_risk,
            exception_remediation=exception_remediation,
        )

        _run_git(["git", "add", target_file], cwd=repo_dir)
        _run_git(["git", "commit", "-m", commit_msg], cwd=repo_dir)

        push_result = subprocess.run(
            ["git", "push", "-u", "origin", branch_name],
            capture_output=True,
            text=True,
            timeout=60,
            cwd=repo_dir,
            env=gitlab_ops.git_env(),
        )

        use_fork = False
        if push_result.returncode != 0:
            fork_url = _ensure_fork(repo_dir)
            if not fork_url:
                return {
                    "status": "failed",
                    "error": f"Push failed and fork creation failed: {push_result.stderr.strip()}",
                    "target_file": target_file,
                    "branch": branch_name,
                    "mr_url": None,
                }
            _run_git(["git", "remote", "add", "fork", fork_url], cwd=repo_dir)
            _run_git(["git", "push", "-u", "fork", branch_name], cwd=repo_dir)
            use_fork = True

        mr_title = _build_mr_title_consolidated(rule, version_specs, environment, vendor_tag)
        mr_body = _build_mr_body_consolidated(
            rule=rule,
            version_specs=version_specs,
            rhoaieng_url=rhoaieng_url,
            reference_url=reference_url,
            spreadsheet_url=spreadsheet_url,
            target_file=target_file,
        )
        mr_create_args = [
            "mr",
            "create",
            "--title",
            mr_title,
            "--description",
            mr_body,
            "--target-branch",
            DEFAULT_BRANCH,
            "--remove-source-branch",
            "-R",
            f"{GITLAB_HOST}/{GITLAB_PROJECT}",
        ]
        if use_fork:
            mr_create_args.extend(["--head", branch_name])

        mr_result = subprocess.run(
            ["glab", *mr_create_args],
            capture_output=True,
            text=True,
            timeout=30,
            cwd=repo_dir,
        )

        if mr_result.returncode != 0:
            return {
                "status": "failed",
                "error": mr_result.stderr.strip() or mr_result.stdout.strip(),
                "target_file": target_file,
                "branch": branch_name,
                "mr_url": None,
                "use_fork": use_fork,
            }

        mr_url = _extract_mr_url(mr_result.stdout + mr_result.stderr)
        return {
            "status": "created",
            "target_file": target_file,
            "branch": branch_name,
            "mr_url": mr_url,
            "component_type": component_type,
            "use_fork": use_fork,
            "versions": [s["version"] for s in version_specs],
            "apply_results": apply_results,
        }
    except subprocess.CalledProcessError as exc:
        return {
            "status": "failed",
            "error": f"Git operation failed: {exc.stderr or exc.stdout}",
            "target_file": target_file,
            "mr_url": None,
        }
    finally:
        import shutil

        shutil.rmtree(workdir, ignore_errors=True)


def _make_branch_name_consolidated(rule: str, version_specs: list[dict]) -> str:
    """Generate a branch name for a consolidated MR (no version suffix)."""
    rule_short = rule.replace(".", "-").replace(":", "-")[:30]
    comp_short = version_specs[0]["components"][0][:20] if version_specs[0]["components"] else "unknown"
    return f"conforma-exception/{rule_short}/{comp_short}"


def _ensure_fork(repo_dir: Path) -> str | None:
    """Create or get existing fork of the upstream project, return authenticated URL."""
    result = subprocess.run(
        [
            "glab",
            "repo",
            "fork",
            GITLAB_PROJECT,
            "--hostname",
            GITLAB_HOST,
            "--clone=false",
        ],
        capture_output=True,
        text=True,
        timeout=30,
        cwd=repo_dir,
    )
    output = result.stdout + result.stderr
    fork_project = _extract_fork_project(output)
    if fork_project:
        return _get_authenticated_repo_url(fork_project)
    if "already exists" in output.lower():
        user_result = subprocess.run(
            ["glab", "auth", "status", "--hostname", GITLAB_HOST],
            capture_output=True,
            text=True,
            timeout=10,
        )
        user_match = re.search(r"Logged in .* as (\S+)", user_result.stdout + user_result.stderr)
        if user_match:
            username = user_match.group(1)
            project_name = GITLAB_PROJECT.split("/")[-1]
            return _get_authenticated_repo_url(f"{username}/{project_name}")
    return None


def _extract_fork_project(output: str) -> str | None:
    """Extract fork project path from glab fork output."""
    match = re.search(rf"{re.escape(GITLAB_HOST)}/([^\s]+?)(?:\.git)?(?:\s|$)", output)
    if match:
        return match.group(1)
    return None


def _make_branch_name(rule: str, version: str, components: list[str]) -> str:
    """Generate a descriptive branch name."""
    rule_short = rule.replace(".", "-").replace(":", "-")[:30]
    comp_short = components[0][:20] if components else "unknown"
    version_short = version.replace("rhoai-", "")
    return f"conforma-exception/{rule_short}/{comp_short}-{version_short}"


def _run_git(cmd: list[str], cwd: Path | None = None, timeout: int = 60) -> subprocess.CompletedProcess:
    """Run a git command, raising on failure.

    Uses gitlab_ops.run_git() to respect GITLAB_SSL_VERIFY settings.
    Injects Bearer token via http.extraheader for authenticated operations
    (clone, push, fetch) so tokens are never embedded in URLs.
    """
    token = _get_gitlab_token()
    needs_auth = any(sub in cmd for sub in ("clone", "push", "fetch", "pull"))
    if token and needs_auth:
        git_idx = cmd.index("git") if "git" in cmd else 0
        cmd = [
            *cmd[: git_idx + 1],
            "-c", f"http.extraheader=Authorization: Bearer {token}",
            *cmd[git_idx + 1 :],
        ]
    return gitlab_ops.run_git(cmd, cwd=cwd, timeout=timeout, check=True)


def _extract_mr_url(output: str) -> str | None:
    """Extract MR URL from glab output."""
    match = re.search(r"(https://[^\s]+merge_requests/\d+)", output)
    return match.group(1) if match else None


