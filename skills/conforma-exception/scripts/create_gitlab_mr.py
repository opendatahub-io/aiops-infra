def modernize_exception_mr(
    rule: str,
    old_effective_until: str,
    version_specs: list[dict],
    environment: str,
    reference_url: str | None = None,
    rhoaieng_url: str | None = None,
    old_components: list[str] | None = None,
    policy_file: str | None = None,
    spreadsheet_url: str | None = None,
    vendor_tag: str | None = None,
    exception_risk: str | None = None,
    exception_remediation: str | None = None,
    dry_run: bool = False,
) -> dict:
    """Create a single MR that removes an unscoped block (no componentNames) and adds new scoped entries.

    Combines remove_exception_from_policy_file() + generate_exception_yaml() in
    one branch/commit so the modernization is atomic.

    version_specs: [{"version": "rhoai-3.3", "components": [...], "effective_until": "..."}, ...]
    """
    if not version_specs:
        return {"status": "failed", "error": "No version_specs provided", "mr_url": None}

    all_components = []
    for spec in version_specs:
        all_components.extend(spec["components"])

    if policy_file:
        target_file = _validate_repo_relative_path(policy_file, "policy-file argument")
    else:
        comp_type = detect_component_type(all_components or old_components or [])
        target_file = get_target_file(comp_type, environment, is_self_service=False)

    WORK_DIR.mkdir(parents=True, exist_ok=True)
    workdir = Path(tempfile.mkdtemp(prefix="conforma-exception-modernize-", dir=WORK_DIR))
    try:
        repo_url = _get_authenticated_repo_url()
        repo_dir = workdir / "repo"
        _run_git(
            ["git", "clone", "--depth=1", "--branch", DEFAULT_BRANCH, repo_url, str(repo_dir)],
            timeout=300,
        )

        pf = repo_dir / target_file
        if not pf.exists():
            return {
                "status": "failed",
                "error": f"Policy file not found: {target_file}",
                "mr_url": None,
            }

        remove_result = remove_exception_from_policy_file(
            pf,
            rule,
            old_effective_until,
            old_components,
        )

        if remove_result["action"] == "not_found":
            return {
                "status": "failed",
                "error": f"Could not find unscoped block to remove: {remove_result['detail']}",
                "mr_url": None,
            }

        apply_results = []
        for spec in version_specs:
            yaml_block = generate_exception_yaml(
                rule=rule,
                components=spec["components"],
                effective_until=spec["effective_until"],
                reference_url=reference_url or "",
                rhoaieng_url=rhoaieng_url,
                rhoai_version=spec["version"],
                is_self_service=False,
                spreadsheet_url=spreadsheet_url,
            )
            result = apply_exception_to_policy_file(
                file_path=pf,
                yaml_block=yaml_block,
                is_self_service=False,
                rule=rule,
                components=spec["components"],
                effective_until=spec["effective_until"],
            )
            apply_results.append(
                {
                    "version": spec["version"],
                    "action": result["action"],
                    "detail": result["detail"],
                }
            )

        versions = [s["version"] for s in version_specs]
        subject = f"Modernize conforma exception: {rule} ({', '.join(versions)})"
        lines = [
            subject,
            "",
            "Replaced unscoped exception (no componentNames) with properly-scoped entries.",
            f"  Rule: {rule}",
            f"  Removed old effectiveUntil: {old_effective_until}",
            f"  Policy file: {target_file}",
        ]
        if exception_risk:
            lines.append(f"  Risk: {exception_risk}")
        if exception_remediation:
            lines.append(f"  Remediation: {exception_remediation}")
        lines.append("")

        for spec in version_specs:
            lines.append(f"  {spec['version']}:")
            lines.append(f"    Components: {', '.join(spec['components'])}")
            lines.append(f"    Effective until: {spec['effective_until']}")
            lines.append("")

        if rhoaieng_url:
            lines.append(f"RHOAIENG: {rhoaieng_url}")
        if reference_url:
            lines.append(f"Reference: {reference_url}")
        if spreadsheet_url:
            lines.append(f"Spreadsheet: {spreadsheet_url}")
        if rhoaieng_url or reference_url or spreadsheet_url:
            lines.append("")

        lines.extend(
            [
                "---",
                f"Generated by: {PROVENANCE_SKILL}",
                f"Source: https://github.com/{PROVENANCE_REPO}",
                f"User: {getpass.getuser()}@{platform.node()}",
            ]
        )
        commit_msg = "\n".join(lines)

        rule_short = rule.replace(".", "-").replace(":", "-")[:30]
        comp_short = version_specs[0]["components"][0][:20] if version_specs[0]["components"] else "unknown"
        branch_name = f"conforma-modernize/{rule_short}/{comp_short}"

        if dry_run:
            return {
                "status": "dry_run",
                "target_file": target_file,
                "remove_result": remove_result,
                "apply_results": apply_results,
                "versions": versions,
                "branch_name": branch_name,
                "mr_url": None,
            }

        _run_git(["git", "checkout", "-b", branch_name], cwd=repo_dir)
        _run_git(["git", "add", target_file], cwd=repo_dir)
        _run_git(["git", "commit", "-m", commit_msg], cwd=repo_dir)

        push_result = subprocess.run(
            ["git", "push", "-u", "origin", branch_name],
            capture_output=True,
            text=True,
            timeout=60,
            cwd=repo_dir,
            env=gitlab_ops.git_env(),
        )

        use_fork = False
        if push_result.returncode != 0:
            fork_url = _ensure_fork(repo_dir)
            if not fork_url:
                return {
                    "status": "failed",
                    "error": f"Push failed and fork creation failed: {push_result.stderr.strip()}",
                    "mr_url": None,
                }
            _run_git(["git", "remote", "add", "fork", fork_url], cwd=repo_dir)
            _run_git(["git", "push", "-u", "fork", branch_name], cwd=repo_dir)
            use_fork = True

        mr_title = f"[RHOAI] Modernize conforma exception: {rule}"
        if vendor_tag:
            mr_title = f"[{vendor_tag}] {mr_title}"

        mr_body_lines = [
            f"## Modernize exception: `{rule}`",
            "",
            "Replaced unscoped exception (no `componentNames`) with properly-scoped entries.",
            "",
            "| Field | Value |",
            "|-------|-------|",
            f"| **Rule** | `{rule}` |",
            f"| **Old effectiveUntil** | `{old_effective_until}` |",
            f"| **Versions** | {', '.join(f'`{v}`' for v in versions)} |",
            f"| **Policy file** | `{target_file}` |",
            "",
        ]

        for spec in version_specs:
            mr_body_lines.append(f"### `{spec['version']}`")
            mr_body_lines.append("")
            mr_body_lines.append(f"**Effective until**: `{spec['effective_until']}`")
            mr_body_lines.append("")
            mr_body_lines.append("**Components**:")
            for comp in spec["components"]:
                mr_body_lines.append(f"- `{comp}`")
            mr_body_lines.append("")

        if rhoaieng_url or reference_url:
            mr_body_lines.append("### References")
            mr_body_lines.append("")
            if rhoaieng_url:
                mr_body_lines.append(f"- **RHOAIENG**: {rhoaieng_url}")
            if reference_url:
                mr_body_lines.append(f"- **Reference**: {reference_url}")
            mr_body_lines.append("")

        mr_body_lines.extend(
            [
                "---",
                "",
                f"*Generated by `{PROVENANCE_SKILL}` | "
                f"[source](https://github.com/{PROVENANCE_REPO}) | "
                f"`{getpass.getuser()}@{platform.node()}`*",
            ]
        )
        mr_body = "\n".join(mr_body_lines)

        mr_create_args = [
            "mr",
            "create",
            "--title",
            mr_title,
            "--description",
            mr_body,
            "--target-branch",
            DEFAULT_BRANCH,
            "--remove-source-branch",
            "-R",
            f"{GITLAB_HOST}/{GITLAB_PROJECT}",
        ]
        if use_fork:
            mr_create_args.extend(["--head", branch_name])

        mr_result = subprocess.run(
            ["glab", *mr_create_args],
            capture_output=True,
            text=True,
            timeout=30,
            cwd=repo_dir,
        )

        if mr_result.returncode != 0:
            return {
                "status": "failed",
                "error": mr_result.stderr.strip() or mr_result.stdout.strip(),
                "mr_url": None,
            }

        mr_url = _extract_mr_url(mr_result.stdout + mr_result.stderr)
        return {
            "status": "created",
            "target_file": target_file,
            "branch": branch_name,
            "mr_url": mr_url,
            "remove_result": remove_result,
            "apply_results": apply_results,
            "versions": versions,
            "use_fork": use_fork,
        }
    except subprocess.CalledProcessError as exc:
        return {
            "status": "failed",
            "error": f"Git operation failed: {exc.stderr or exc.stdout}",
            "mr_url": None,
        }
    finally:
        import shutil

        shutil.rmtree(workdir, ignore_errors=True)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Create GitLab MR for Conforma exception")
    parser.add_argument("--rule", required=True)
    parser.add_argument("--components", default=None, help="Comma-separated (single-version mode)")
    parser.add_argument("--effective-until", default=None, help="Single-version mode")
    parser.add_argument("--reference-url", default=None, help="PSX/OCPEXCEPT ticket URL")
    parser.add_argument("--reference-title", default=None, help="PSX/OCPEXCEPT ticket title")
    parser.add_argument("--rhoaieng-url", default=None)
    parser.add_argument("--remediation-plan-url", default=None)
    parser.add_argument("--rhoai-version", default=None, help="Single-version mode")
    parser.add_argument("--environment", required=True, choices=["prod", "stage"])
    parser.add_argument("--spreadsheet-url", default=None, help="Tracking spreadsheet URL (YAML comment)")
    parser.add_argument(
        "--self-service",
        action="store_true",
        help="Target exceptions/ dir (set automatically by orchestrator from workflow)",
    )
    parser.add_argument("--image-ref", default=None, help="SHA digest for weekday_restriction")
    parser.add_argument(
        "--vendor-tag",
        default=None,
        help="Vendor/distinguisher tag prepended to MR title (e.g. AMD, Intel)",
    )
    parser.add_argument("--update-mr", default=None, help="Existing MR branch to update")
    parser.add_argument(
        "--version-specs-json",
        default=None,
        help=(
            "JSON array of version specs for consolidated mode. Each entry: "
            '{"version": "rhoai-X.Y", "components": [...], "effective_until": "..."}. '
            "When provided, --components/--effective-until/--rhoai-version are ignored."
        ),
    )
    parser.add_argument("--template", default=None, help="Template category ID from exception_templates.yaml")
    parser.add_argument(
        "--justification", default=None, help="Justification template ID (e.g., dev_preview, code_frozen)"
    )
    parser.add_argument("--exception-risk", default=None, help="Exception risk text (overrides template)")
    parser.add_argument("--exception-remediation", default=None, help="Exception remediation text (overrides template)")
    parser.add_argument(
        "--remove-expired-exception",
        action="store_true",
        help="Remove an expired exception instead of adding/extending one",
    )
    parser.add_argument(
        "--modernize-expired-exception",
        action="store_true",
        help="Remove unscoped block (no componentNames) and add new scoped entries in one MR. "
        "Requires --version-specs-json for the new entries.",
    )
    parser.add_argument("--clone-dir", default=None, help="Existing repo clone to use (remove-expired-exception mode)")
    parser.add_argument(
        "--policy-file",
        default=None,
        help="Override auto-detected policy file path within the repo "
        "(e.g. config/.../fbc-rhoai-prod.yaml). Required for unscoped "
        "FBC exceptions where component names are absent.",
    )
    parser.add_argument("--dry-run", action="store_true")
    return parser.parse_args()


def main() -> int:
    args = parse_args()

    if args.remove_expired_exception:
        if not args.rule or not args.effective_until or not args.rhoai_version:
            print(
                "Error: --rule, --effective-until, and --rhoai-version are required "
                "for --remove-expired-exception mode.",
                file=sys.stderr,
            )
            return 1
        components = [c.strip() for c in args.components.split(",")] if args.components else None
        result = remove_expired_mr(
            rule=args.rule,
            effective_until=args.effective_until,
            rhoai_version=args.rhoai_version,
            environment=args.environment,
            components=components,
            reference_url=args.reference_url,
            clone_dir=args.clone_dir,
            policy_file=args.policy_file,
            dry_run=args.dry_run,
        )
        print(json.dumps(result, indent=2))
        return 0 if result["status"] in ("created", "dry_run", "not_found") else 1

    if args.modernize_expired_exception:
        if not args.rule or not args.effective_until:
            print(
                "Error: --rule and --effective-until are required for --modernize-expired-exception mode.",
                file=sys.stderr,
            )
            return 1
        if not args.version_specs_json:
            print(
                "Error: --version-specs-json is required for --modernize-expired-exception "
                "(defines the new scoped entries to create).",
                file=sys.stderr,
            )
            return 1
        old_components = [c.strip() for c in args.components.split(",")] if args.components else None
        version_specs = json.loads(args.version_specs_json)
        result = modernize_exception_mr(
            rule=args.rule,
            old_effective_until=args.effective_until,
            version_specs=version_specs,
            environment=args.environment,
            reference_url=args.reference_url,
            rhoaieng_url=args.rhoaieng_url,
            old_components=old_components,
            policy_file=args.policy_file,
            spreadsheet_url=args.spreadsheet_url,
            vendor_tag=args.vendor_tag,
            exception_risk=args.exception_risk,
            exception_remediation=args.exception_remediation,
            dry_run=args.dry_run,
        )
        print(json.dumps(result, indent=2))
        return 0 if result["status"] in ("created", "dry_run") else 1

    if not args.reference_url:
        print(
            "Error: --reference-url is required for add/extend modes.",
            file=sys.stderr,
        )
        return 1

    # --- Resolve template + justification if provided ---
    if args.template:
        from create_jira_ticket import resolve_template

        versions_str = args.rhoai_version or ""
        versions_list = [v.strip() for v in versions_str.split(",") if v.strip()]
        rule_key = args.rule.split(":", 1)[1] if ":" in args.rule else args.rule
        components_str = args.components or ""
        components_list = [c.strip() for c in components_str.split(",") if c.strip()]
        template_vars = {
            "rule": args.rule,
            "rule_key": rule_key,
            "components": ", ".join(components_list),
            "component_count": str(len(components_list)),
            "versions": ", ".join(versions_list) if versions_list else versions_str,
            "version_count": str(len(versions_list)) if versions_list else "1",
            "vendor": args.vendor_tag or "",
            "rhoaieng_exception_approval_url": args.rhoaieng_url or args.reference_url or "",
            "rhoaieng_jira_violation_url": args.remediation_plan_url or args.rhoaieng_url or "",
            "remediation_plan_url": args.remediation_plan_url or "",
            "effective_until": args.effective_until or "",
        }
        resolved = resolve_template(
            args.template,
            template_vars,
            justification_id=args.justification,
        )
        if not args.exception_risk:
            args.exception_risk = resolved.get("risk")
        if not args.exception_remediation:
            args.exception_remediation = resolved.get("remediation")

    # Consolidated mode: single MR for all versions
    if args.version_specs_json:
        version_specs = json.loads(args.version_specs_json)
        if args.update_mr:
            result = update_consolidated_mr(
                branch_name=args.update_mr,
                rule=args.rule,
                version_specs=version_specs,
                reference_url=args.reference_url,
                rhoaieng_url=args.rhoaieng_url,
                environment=args.environment,
                is_self_service=args.self_service,
                reference_title=args.reference_title,
                spreadsheet_url=args.spreadsheet_url,
                vendor_tag=args.vendor_tag,
                exception_risk=args.exception_risk,
                exception_remediation=args.exception_remediation,
                policy_file=args.policy_file,
                dry_run=args.dry_run,
            )
        else:
            result = create_consolidated_mr(
                rule=args.rule,
                version_specs=version_specs,
                reference_url=args.reference_url,
                rhoaieng_url=args.rhoaieng_url,
                environment=args.environment,
                is_self_service=args.self_service,
                reference_title=args.reference_title,
                spreadsheet_url=args.spreadsheet_url,
                vendor_tag=args.vendor_tag,
                exception_risk=args.exception_risk,
                exception_remediation=args.exception_remediation,
                policy_file=args.policy_file,
                dry_run=args.dry_run,
            )
        print(json.dumps(result, indent=2))
        return 0 if result["status"] in ("created", "updated", "dry_run") else 1

    # Single-version mode (backward compatible)
    if not args.components or not args.effective_until or not args.rhoai_version:
        print(
            "Error: --components, --effective-until, and --rhoai-version are required "
            "in single-version mode (when --version-specs-json is not provided).",
            file=sys.stderr,
        )
        return 1

    components = [c.strip() for c in args.components.split(",")]
    is_weekday = args.rule == "schedule.weekday_restriction"

    if args.update_mr:
        result = update_mr(
            branch_name=args.update_mr,
            rule=args.rule,
            components=components,
            effective_until=args.effective_until,
            reference_url=args.reference_url,
            rhoaieng_url=args.rhoaieng_url,
            rhoai_version=args.rhoai_version,
            environment=args.environment,
            is_self_service=args.self_service,
            is_weekday_restriction=is_weekday,
            image_ref=args.image_ref,
            reference_title=args.reference_title,
            spreadsheet_url=args.spreadsheet_url,
            vendor_tag=args.vendor_tag,
            exception_risk=args.exception_risk,
            exception_remediation=args.exception_remediation,
            policy_file=args.policy_file,
            dry_run=args.dry_run,
        )
    else:
        result = create_mr(
            rule=args.rule,
            components=components,
            effective_until=args.effective_until,
            reference_url=args.reference_url,
            rhoaieng_url=args.rhoaieng_url,
            rhoai_version=args.rhoai_version,
            environment=args.environment,
            is_self_service=args.self_service,
            is_weekday_restriction=is_weekday,
            image_ref=args.image_ref,
            reference_title=args.reference_title,
            spreadsheet_url=args.spreadsheet_url,
            vendor_tag=args.vendor_tag,
            exception_risk=args.exception_risk,
            exception_remediation=args.exception_remediation,
            policy_file=args.policy_file,
            dry_run=args.dry_run,
        )
    print(json.dumps(result, indent=2))
    return 0 if result["status"] in ("created", "updated", "dry_run") else 1


if __name__ == "__main__":
    sys.exit(main())
